<?php

namespace App\Http\Controllers\Api\Agent;

use App\Http\Controllers\Controller;
use App\Models\App;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Log;

class AgentJoinLinkController extends Controller
{
    /**
     * Get active shareable join link for an application.
     *
     * GET /api/agent/v1/apps/{app}/join-link
     */
    public function show(Request $request, string $appId): JsonResponse
    {
        $app = App::where('id', $appId)->orWhere('slug', $appId)->firstOrFail();
        $link = $app->joinLinks()->where('is_active', true)->first()
            ?? $app->joinLinks()->latest()->first();

        return response()->json([
            'success' => true,
            'data' => $link ? $this->formatJoinLink($link) : null,
        ]);
    }

    /**
     * Enable, disable, or configure shareable join link.
     *
     * POST /api/agent/v1/apps/{app}/join-link
     */
    public function toggle(Request $request, string $appId): JsonResponse
    {
        $app = App::where('id', $appId)->orWhere('slug', $appId)->firstOrFail();

        $validated = $request->validate([
            'is_active' => 'required|boolean',
            'role' => 'nullable|string|in:enumerator,supervisor,viewer',
        ]);

        $link = $app->joinLinks()->where('is_active', true)->first();

        if ($validated['is_active']) {
            if (! $link) {
                $link = $app->joinLinks()->create([
                    'role' => $validated['role'] ?? 'enumerator',
                    'is_active' => true,
                    'created_by' => $request->user()?->id,
                ]);
            } elseif (! empty($validated['role'])) {
                $link->update(['role' => $validated['role']]);
            }
        } else {
            if ($link) {
                $link->update(['is_active' => false]);
            }
        }

        $fresh = $link ? $link->fresh() : null;

        Log::info('[AGENT_MUTATION] Join link toggled by Agent', [
            'app_id' => $app->id,
            'is_active' => $validated['is_active'],
            'role' => $fresh?->role,
        ]);

        return response()->json([
            'success' => true,
            'message' => $validated['is_active'] ? 'Join link enabled' : 'Join link disabled',
            'data' => $fresh ? $this->formatJoinLink($fresh) : null,
        ]);
    }

    /**
     * Regenerate token, invalidating any previous shareable links.
     *
     * POST/DELETE /api/agent/v1/apps/{app}/join-link/regenerate
     */
    public function regenerate(Request $request, string $appId): JsonResponse
    {
        $app = App::where('id', $appId)->orWhere('slug', $appId)->firstOrFail();
        $role = $request->input('role', 'enumerator');

        $app->joinLinks()->update(['is_active' => false]);

        $newLink = $app->joinLinks()->create([
            'role' => in_array($role, ['enumerator', 'supervisor', 'viewer'], true) ? $role : 'enumerator',
            'is_active' => true,
            'created_by' => $request->user()?->id,
        ]);

        Log::info('[AGENT_MUTATION] Join link regenerated by Agent', [
            'app_id' => $app->id,
            'new_token' => substr($newLink->token, 0, 8).'...',
        ]);

        return response()->json([
            'success' => true,
            'message' => 'New join link generated successfully',
            'data' => $this->formatJoinLink($newLink),
        ]);
    }

    private function formatJoinLink($link): array
    {
        $rawClient = env('CERDAS_CLIENT_URL', env('CERDAS_APP_URL', env('APP_URL', 'https://app.dvlpid.my.id')));
        $clientUrl = str_contains($rawClient, 'api.') ? str_replace('api.', 'app.', $rawClient) : $rawClient;

        return [
            'id' => $link->id,
            'app_id' => $link->app_id,
            'token' => $link->token,
            'role' => $link->role,
            'is_active' => (bool) $link->is_active,
            'full_url' => rtrim($clientUrl, '/').'/join/'.$link->token,
            'expires_at' => $link->expires_at?->toIso8601String(),
            'created_at' => $link->created_at?->toIso8601String(),
        ];
    }
}
